const fs = require("fs");
const [,, file] = process.argv;
const b = fs.readFileSync(file);
const magics = [
  ["PK\\x03\\x04 zip", [0x50, 0x4b, 0x03, 0x04]],
  ["gzip 1f8b", [0x1f, 0x8b]],
  ["PNG", [0x89, 0x50, 0x4e, 0x47]],
  ["SQLite", [0x53, 0x51, 0x4c, 0x69, 0x74, 0x65, 0x20, 0x66, 0x6f, 0x72, 0x6d, 0x61, 0x74, 0x20, 0x33, 0x00]],
  ["bplist", [0x62, 0x70, 0x6c, 0x69, 0x73, 0x74]],
  ["BSJB .NET-meta", [0x42, 0x53, 0x4a, 0x42]],
  ["PEM -----BEGIN", [0x2d, 0x2d, 0x2d, 0x2d, 0x2d, 0x42, 0x45, 0x47, 0x49, 0x4e]],
  ["SQLite-journal", [0xd9, 0xd5, 0x05, 0xf9, 0x20, 0xa1, 0x63, 0xd7]],
];
for (const [name, sig] of magics) {
  const hits = [];
  for (let i = 0; i + sig.length < b.length && hits.length < 15; i++) {
    let ok = true;
    for (let k = 0; k < sig.length; k++) { if (b[i + k] !== sig[k]) { ok = false; break; } }
    if (ok) { hits.push(i); i += 64; }
  }
  console.log(name + ": " + hits.length + (hits.length ? " @ " + hits.slice(0, 8).map((h) => "0x" + h.toString(16)).join(" ") : ""));
}
